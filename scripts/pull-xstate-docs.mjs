import fs from "node:fs";
import path from "node:path";
import { spawn } from "node:child_process";
import { fileURLToPath } from "node:url";

const ROOT_DIR = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const BASE_URL = "https://stately.ai";
const TARGET_DIR = path.join(ROOT_DIR, "docs", "xstate", "upstream");
const CURL_COMMAND = process.platform === "win32" ? "curl.exe" : "curl";
const CONCURRENCY = 6;

function runCurl(url, outputPath) {
  return new Promise((resolve, reject) => {
    const child = spawn(CURL_COMMAND, [
      "-fsSL",
      "--retry",
      "3",
      "--retry-delay",
      "1",
      url,
      "-o",
      outputPath,
    ], { stdio: "inherit" });
    child.once("error", reject);
    child.once("exit", (code, signal) => {
      if (code === 0) {
        resolve();
        return;
      }
      reject(new Error(`curl failed for ${url}${signal ? ` (${signal})` : ` (exit ${code})`}`));
    });
  });
}

function readV6Paths(index) {
  const paths = Array.from(index.matchAll(/\((\/docs\/xstate\/v6\/[^)]+\.mdx)\)/g), (match) => match[1]);
  return Array.from(new Set(paths)).filter((docPath) => !/\/(react|solid|svelte|vue|angular|store)\//.test(docPath));
}

function writeReadme(paths) {
  const lines = [
    "# XState v6 Upstream Documentation",
    "",
    "This directory is generated by `pnpm docs:xstate` using Stately's published XState v6 documentation.",
    "",
    `- Source index: ${BASE_URL}/llms.txt`,
    `- Source pages: ${BASE_URL}/docs/xstate/v6/`,
    `- Downloaded pages: ${paths.length}`,
    "- Runtime dependency: `xstate@6.0.0-alpha.59`",
    "",
    "The files in this directory are reference material. Project workflow contracts live in `../machines.md` and are enforced against `lib/xstate/**/machine.ts`.",
    "",
  ];
  fs.writeFileSync(path.join(TARGET_DIR, "README.md"), lines.join("\n"), "utf-8");
}

async function main() {
  fs.rmSync(TARGET_DIR, { recursive: true, force: true });
  fs.mkdirSync(TARGET_DIR, { recursive: true });

  const indexPath = path.join(TARGET_DIR, "llms.txt");
  await runCurl(`${BASE_URL}/llms.txt`, indexPath);
  const index = fs.readFileSync(indexPath, "utf-8");
  const paths = readV6Paths(index);

  const queue = [...paths];
  let completed = 0;
  let failed = 0;

  async function worker() {
    while (queue.length > 0) {
      const docPath = queue.shift();
      if (!docPath) return;
      const targetPath = path.join(TARGET_DIR, docPath.replace(/^\//, ""));
      fs.mkdirSync(path.dirname(targetPath), { recursive: true });
      try {
        await runCurl(`${BASE_URL}${docPath}`, targetPath);
        completed += 1;
        if (completed % 10 === 0 || completed === paths.length) {
          console.log(`Downloaded ${completed}/${paths.length} XState v6 pages`);
        }
      } catch (error) {
        failed += 1;
        console.error(error instanceof Error ? error.message : String(error));
      }
    }
  }

  await Promise.all(Array.from({ length: CONCURRENCY }, () => worker()));
  fs.writeFileSync(
    path.join(TARGET_DIR, "source-manifest.json"),
    `${JSON.stringify({ source: `${BASE_URL}/llms.txt`, pages: paths }, null, 2)}\n`,
    "utf-8",
  );
  writeReadme(paths);
  console.log(`Finished: ${completed} succeeded, ${failed} failed.`);
  if (failed > 0) process.exitCode = 1;
}

main().catch((error) => {
  console.error(error instanceof Error ? error.message : String(error));
  process.exitCode = 1;
});
